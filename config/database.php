use Illuminate\Support\Str;

return [
    'default' => env('DB_CONNECTION', 'mysql'),
    'connections' => [
        'mysql' => [
            'driver' => 'mysql',
            'url' => env('DB_URL'),
            'host' => env('DB_HOST', '127.0.0.1'),
            'port' => env('DB_PORT', '3306'),
            'database' => env('DB_DATABASE', 'studybuddy'),
            'username' => env('DB_USERNAME', 'root'),
            'password' => env('DB_PASSWORD', ''),
            'unix_socket' => env('DB_SOCKET', ''),
            'charset' => env('DB_CHARSET', 'utf8mb4'),
            'collation' => env('DB_COLLATION', 'utf8mb4_unicode_ci'),
            'prefix' => '',
            'prefix_indexes' => true,
            'strict' => true,
            'engine' => null,
            // PHP 8.5 deprecates PDO::MYSQL_ATTR_SSL_CA in favour of
            // Pdo\Mysql::ATTR_SSL_CA. Only touch either constant when a CA
            // file is actually configured, so no deprecation is emitted on the
            // usual setups that do not use TLS to MySQL.
            'options' => (function (): array {
                $certificateAuthority = env('MYSQL_ATTR_SSL_CA');

                if (! extension_loaded('pdo_mysql') || ! $certificateAuthority) {
                    return [];
                }

                $attribute = class_exists(\Pdo\Mysql::class)
                    ? \Pdo\Mysql::ATTR_SSL_CA
                    : constant('PDO::MYSQL_ATTR_SSL_CA');

                return [$attribute => $certificateAuthority];
            })(),
        ],
    ],
    'migrations' => [
        'table' => 'migrations',
        'update_date_on_publish' => true,
    ],
    'redis' => [
        'client' => env('REDIS_CLIENT', 'phpredis'),
        'options' => [
            'cluster' => env('REDIS_CLUSTER', 'redis'),
